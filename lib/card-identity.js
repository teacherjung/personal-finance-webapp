/**
 * 可以拿來當「機構名證據」的**逐列**文字＝**第一筆交易列之前**的那些列。
 *
 * ⚠️ 回傳的是 `string[]` 而不是一整串——**跨列拼字必須在結構上不可能**，不是靠註解保證。
 *    前一版回傳 `join('\n')` 的整串，於是 `/台\s*新/` 的 `\s` 吃掉換行、把兩列拼成一個行名
 *    （Codex #518 r1#1 實測）。註解當時寫的是「逐列 squash、換行保留」——**那句話擋不住正規式**。
 *
 * ⚠️ 為什麼是「第一筆交易列之前」而不是「所有沒被消耗、又不像交易列的列」（前一版）：
 *    明細區後面會出現**沒被任何解析器消耗、又不像交易列的續行**（例如單獨一列的
 *    「富邦人壽保險費」），它們是**商店名**，前一版讓它們重新取得投票權——直接推翻本檔宣稱的
 *    「商店名一律沒有投票權」（Codex #518 r1#1 第二個實測案例）。機構名印在表頭區，商店名印在明細區；
 *    用「第一筆交易列」當分界，兩者才真的分得開。
 *
 * ⚠️ 誠實劃界：**只印在頁尾的機構名認不出來** ⇒ 落到分支④（不猜、不自動歸卡、畫面警語）。
 *    這是刻意選的失敗方向——代價是使用者多按一次選卡，不是錢記錯。
 *
 * 🔬 **這個代價已經在真帳單上量過，而且真的踩到了**（2026-08-27，使用者的 5 份真實富邦信用卡帳單：
 *    官網「帳單明細查詢」下載版 3 份＋郵寄電子帳單 2 份）：
 *    - 官網版：整份**一個「富邦」都沒有**（連裸的字串都搜不到）。
 *    - 郵寄版：第一次出現「富邦」在第 96／119 列，而分界在第 7 列——**遠在表頭區之後**
 *      （而且那一列是旅遊平安險的說明文字，不是抬頭）。
 *    ⇒ 這 5 份現在**全部落到分支④**：明細照樣正確讀出（56／75 筆等），但不掛機構名、要使用者自己選卡。
 *    ⇒ **本支之前是「碰巧對的」**：舊做法數全文行名，數到的正是第 96 列那段說明文字。
 *    ⇒ **不要為了救它而放寬**：放寬到「整份都算證據」就是回到 r1#1b 被打穿的那一版；
 *      放寬到「裸的富邦」就撞上香港富邦。要真的救它只能靠版面指紋，而版面指紋的字面
 *      （欄名組合）在只有一家的樣本下無法證明它不是**全台通用**——那正是本支撤回過一次的錯誤。
 *
 * ✅ **這不是新發明，是對齊既有前例**：銀行對帳單那條路早就這樣做了——契約
 *    `docs/contracts/income-expense.md` 的機構名節（Codex r28#2）白紙黑字寫著「銀行名必須來自
 *    標題類列，交易與其續行全在表頭之後＝**結構性排除**」，理由也一樣（別家帳單冒名解析會讓
 *    機構戳與去重鍵全錯）。卡片這條路缺的就是這一層。
 *
 * @param {string[][]} lines @param {Set<number>} used 解析器自報消耗掉的列索引
 * @returns {string[]} 表頭區各列的 squash 後文字（逐列，不合併）
 */
export function evidenceRows(lines, used) {
  const u = used instanceof Set ? used : new Set();
  const rows = lines || [];
  // 分界＝第一列「被解析器消耗」或「長得像交易列」的位置。兩個條件都要：
  //   前者抓真的被讀成明細的列；後者抓「我們讀不動、但確實是交易列」的版面（否則分界會滑到文件末尾）。
  let boundary = rows.length;
  for (let i = 0; i < rows.length; i++) {
    if (u.has(i) || looksLikeTxRow(rows[i])) { boundary = i; break; }
  }
  return rows.slice(0, boundary).map((l) => squash((l || []).join('')));
}

/**
 * 判斷這份帳單的機構身分。
 * @param {string[][]} lines
 * @param {Set<number>} used 兩支解析器消耗掉的列索引**聯集**（與「最後採用哪一支」無關 ⇒ 不循環）
 * @returns {{ bank: string, bankEvidence: 'header'|'none', own: string[], other: string[] }}
 */
export function identifyIssuer(lines, used) {
  const rows = evidenceRows(lines, used);
  // ⚠️ **逐列比對**：任何「把 rows 併成一串再比」的寫法都會把跨列通道打開（r1#1 的原病）。
  const own = OWN_ISSUERS.filter((o) => rows.some((t) => o.re.test(t))).map((o) => o.bank);
  const other = OTHER_ISSUERS.filter((n) => rows.some((t) => t.includes(n)));
  // 只有「唯一一家自家、且沒有任何別家」才敢掛機構名。其餘一律不猜。
  const sure = own.length === 1 && other.length === 0;
  return { bank: sure ? own[0] : '', bankEvidence: sure ? 'header' : 'none', own, other };
}

/**
 * 機構名的證據種類。
 * - `header`＝PDF：機構名出現在「解析器沒消耗掉、又不像交易列」的列上（本檔的判準）
 * - `xlsx-template`＝XLSX：內建欄位版面對得上。⚠️ 這**比 header 弱**——XLSX 那條路是靠
 *   **欄位位置**（第 0/2/4/7 欄）認的，沒有任何欄名或機構名比對，所以別家 XLSX 只要欄序不同
 *   就會靜靜抄錯欄。刻意給它一個**不同的名字**而不是混進 `header`，是為了讓「這份的身分有多可靠」
 *   在型別上就看得出來，而不是靠讀註解。
 * - `none`＝沒有夠格的證據 ⇒ `bank` 必須是空字串
 * @typedef {'header'|'xlsx-template'|'none'} BankEvidence
 */

/**
 * 輸出不變量——違反代表**我們的程式有 bug**（不是使用者的檔案有問題），所以丟 500。
 *
 * ⚠️ **刻意 throw 而不是把值夾正**。夾正（`seal`）會讓「把身分算錯」與「把值修好」互相蒙眼，
 *    屬性測試就變成恆真——工作流的對抗驗證實測過：改成夾正之後，「挑筆數多者」那顆突變全綠。
 *
 * @param {{ bank: string, bankEvidence: string, rows: unknown[], code?: string|null }} r
 */
export function assertCardIdentityInvariants(r) {
  const bad = (/** @type {string} */ why) => {
    throw Object.assign(new Error(`卡片身分不變量被違反：${why}`), { status: 500, code: 'card_identity_invariant' });
  };
  if (r.code && (r.rows.length !== 0 || r.bank !== '')) bad('丟錯時不得同時交出列或機構名');
  if (r.bank !== '' && r.bankEvidence === 'none') bad('掛了機構名就必須說得出證據來源');
  if (!['header', 'xlsx-template', 'none'].includes(r.bankEvidence)) bad(`證據種類 ${r.bankEvidence} 不是已知的三種之一`);
  if (r.bank !== '' && !OWN_ISSUERS.some((o) => o.bank === r.bank)) bad(`機構名 ${r.bank} 不在內建範本清單裡`);
  if (r.bankEvidence === 'none' && r.bank !== '') bad('沒有證據就不得掛機構名');
  return r;
}
