export function cardCertainlyNot(card, bank) {
  if (!bank) return false;
  const listed = codedIssuer(card);   // ⚠️ 不是 issuerById——兩欄矛盾時不採信代號，見 codedIssuer 檔頭
  if (listed) return listed.bank !== bank;
  return issuerCertainlyNot(card?.issuer, bank);
}

