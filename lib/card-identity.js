/**
 * 一張卡片的**發卡行**是不是我們認得的那兩家。
 *
 * ## 兩把尺，一個共用的樣式
 *
 * ⚠️ **與「帳單是誰印的」共用同一組 `OWN_ISSUERS` 樣式**（撞名處理只有一個地方，不會走鐘），
 *    但**卡片欄位另外先查一次可選清單**（`public/modules/card-issuers.js`）——所以不是「完全同一把尺」。
 *    兩個資料域的輸入性質本來就不同：抬頭是 PDF 文字（格與格的接縫會長出假行名，所以要錨定＋佐證詞），
 *    卡片欄位是**使用者從清單挑的**（挑「台北富邦銀行」或「富邦銀行（香港）」是兩個不同的選項），
 *    外加清單化之前留下來的自由文字。
 * ⚠️ 這條路守的是錢：`String(issuer).includes(bank)`（base 的寫法）會讓
 *    「富邦銀行（香港）有限公司」對富邦帳單為真（base 的 `issuerMatchesBank`，2026-09-02 改名為 `cardMatchesBank`）
 *    ⇒ 台北富邦的帳單＋同末四碼的
 *    香港富邦卡 ⇒ 直接自動歸到那張香港卡（Codex #518 r3#2 實測）。`lib/bank-alias.js:17` 早就記著這個撞名危害。
 * ⚠️ 不能改用 `lib/bank-alias.js` 的 `sameBank`：那支只把**台新**收斂成短名，
 *    `sameBank('台北富邦銀行', '富邦')` 是 `false` ⇒ 會把富邦整個弄壞（實測）。
 *
 * @param {unknown} issuer @returns {string} '台新'|'富邦'|''（認不出）
 */
export function issuerBank(issuer) {
  const t = squash(String(issuer ?? ''));
  // ① 可選清單優先（2026-08-28，William 指派把發卡行從自由文字改成清單）。
  // ⚠️ **這一步不是「多一層保險」，它是承重的**：清單上的 `aka` 收得住既有的自由文字短名
  //    （「台新」「台北富邦」——`OWN_ISSUERS` 的樣式刻意要求錨定＋佐證詞，短名對不上），
  //    而**不接受短名**曾被判定為相對 base 的功能退化（Codex #518 r8#1）。拿掉這一步，
  //    既有的「台新」卡每期都要手選。
  const named = issuersNamed(t);
  if (named.length === 1) return named[0].bank;
  // ⚠️ **兩家以上都自稱這個寫法 ⇒ 不猜、也不落回樣式比對**。今天唯一的實例是「富邦」「富邦銀行」：
  //    香港富邦官方自稱「富邦銀行」、台北富邦官方沿革同樣記載這個簡稱（William 2026-08-28 查證），
  //    所以把香港卡的發卡行填成精確的「富邦」是合理且可達的輸入。判成台北富邦＝**錢記到錯的卡**；
  //    判不出來＝使用者多按一次選卡。兩害相權取後者，而清單就是那張卡的永久解（挑一項就沒有歧義了）。
  // ⚠️ **誠實劃界**：今天這一格的**行為**與「落回樣式比對」分辨不出來——「富邦」「富邦銀行」
  //    在 `OWN_ISSUERS` 底下本來就都不命中（樣式要求「台北富邦…銀行」），所以兩條路都回 `''`，
  //    突變成 `if (named.length) { /* 什麼都不做 */ }` 不會有任何一題轉紅。留著是因為它是這條規則的
  //    **正文**：日後只要有人把某一家的正式名稱登記成另一家的 `aka`，落回樣式比對就會給出錯的那一家。
  //    **不要把它當成保證**——承重的不變量是上面那句「兩家以上就不判身分」，而它由
  //    `test/card-issuers.test.js` 的「富邦／富邦銀行必須被兩家宣稱」那一題釘住資料面。
  if (named.length) return '';
  // ② 清單裡沒有這個寫法（自訂機構、或清單化之前的自由文字）⇒ 退回樣式比對。
  const hit = OWN_ISSUERS.filter((o) => o.re.test(t));
  // ⚠️ 「撞到兩家＝認不出」是 fail-closed 的**冗餘保險**：樣式都錨定在字串開頭，
  //    一個字串不可能同時以「台新…」與「台北富邦…」開頭 ⇒ 這一格目前**不可達**，
  //    突變測試也證實把它放寬成 `hit.length ?` 沒有任何一題會紅（等價突變）。
  //    留著是因為它零成本、而且樣式日後若拿掉錨定它就會變成承重的；但**不要當成保證**。
  return hit.length === 1 ? hit[0].bank : '';
}

/**
 * 一張**卡片**的發卡行是哪一家——2026-09-02 起這才是對卡那條路的入口（`issuerBank` 降級成它的退路）。
 *
 * ## 一張卡只有一把尺，由「有沒有代號」決定是哪一把
 *
 * ①**代號查得到**（`card.issuerId` 是我們發過的代號）⇒ 直接回那一家的 `bank`，
 *   `card.issuer` 那串字**一個字元都不看**。這是本支的全部價值：身分不再是從顯示字串算出來的，
 *   所以清單改名、`issuerNameKey` 被人動手腳、`OWN_ISSUERS` 樣式沒有結尾錨——這些都影響不到它。
 * ②**代號查不到**（沒有／空字串／非字串／不認得的代號）⇒ **視同這張卡沒有代號**，退回 `issuerBank`
 *   的文字判準（清單名稱／別名 → `OWN_ISSUERS` 樣式）。
 *
 * ⚠️ **不是「兩把尺比一比」**：兩條路互斥，命中①就不會走②。會「兩把尺同時說話」的設計
 *    （例如代號說台新、文字說富邦，然後挑一個）正是這個 repo 反覆踩到的病。
 * ⚠️ **不認得的代號為什麼是「退回文字」而不是「一律擋」**：擋的話，一筆從備份匯入進來的壞代號
 *    會讓那張卡從此判不出身分、連帶把**整個銀行的單卡自動歸**都拖下水（`cardCertainlyNot` 的代價）。
 *    退回文字＝與升級前逐字相同的行為，**零回歸**——這是 William 2026-09-02 裁示
 *    「照舊自動＋提示升級」的直接後果。
 * ⚠️ **誠實劃界：本支沒有關掉文字那條路上的洞**。沒有代號的卡（清單化之前的舊卡、選「其他」自己
 *    打的機構、`bank-import.js` 自動建的簽帳金融卡）照舊走②，②的已知洞（`issuerNameKey` 可以偷偷
 *    授予身分／「台北富邦銀行（香港）」前綴命中成富邦）對它們**仍然存在**。本支關掉的是走①的那些卡。
 *
 * @param {{ issuer?: unknown, issuerId?: unknown } | null | undefined} card
 * @returns {string} '台新'|'富邦'|''（認不出）
 */
export function cardIssuerBank(card) {
  const listed = codedIssuer(card);
  if (listed) return listed.bank;
  return issuerBank(card?.issuer);
}


/**
 * 這張卡的發卡行**確定不是** `bank` 這一家——分支②「該銀行單卡就自動歸」的**前提**，顯式化成判準。
 *
 * ## 為什麼是「確定不是」而不是「可能是」（William 2026-08-28 裁示「擋：不確定就問我」）
 *
 * `issuerBank` 判不出身分時回 `''`，服務層的 `cardMatchesBank` 因此回 `false`，那張卡就**被移出**
 * `bankCards`（`lib/services/statement-import.js` 的族群過濾）。但下游的分支②是一個**唯一性**判準
 * （族群只剩一張就自動歸卡）——**把一個候選移出族群，會把「兩張、該問使用者」靜靜變成
 * 「只剩一張、自動歸卡」**：候選變少反而變成自動決定，方向與「不確定就問使用者」相反。
 *
 * 「該銀行只有一張卡 ⇒ 帳單一定是這張」這個推論，成立的前提是**其餘每一張卡都確定不是這家**。
 * 前一版（#520 的 `issuerMaybeBank`）只把「歧義寫法、而歧義的其中一家正是 `bank`」算進守門，
 * 於是**判不出身分**的卡（發卡行沒填、填了清單與樣式都認不出的字、壞資料 `String()` 定型後
 * 仍認不出的）仍被無聲排除——那張卡如果就是帳單這家的（新建卡還沒填發卡行是最常見的形狀），
 * 帳單會自動記到**另一張**有填的卡上。所以判準反過來寫：**證明得了「確定是別家」的才可以出局**，
 * 證明不了的一律把自動歸擋下來、並且要出現在候選清單裡（使用者看不到那張卡就選不到它）。
 *
 * ## 判準（誰算「確定是別家」）
 *
 * - **清單認得這個寫法**（`issuersNamed` 有命中）⇒ 所有宣稱者都不是 `bank` 才算確定別家。
 *   ・唯一宣稱者是玉山／遠東商銀／台北富邦（對台新帳單）⇒ 確定別家 ⇒ 照樣自動歸（不過度 fail-closed）。
 *     ⚠️ 這裡是 `bank: ''` 的清單機構與「判不出」分開的地方：「遠東商銀」不是判不出，
 *     是**認得出、但那家沒有內建範本**——它確定不是台新，不該擋台新的自動歸。
 *   ・歧義且其中一家正是 `bank`（「富邦」對富邦帳單）⇒ 不確定 ⇒ 擋（＝前一版 `issuerMaybeBank` 的射程）。
 *   ・歧義但都不是 `bank`（「富邦」對台新帳單）⇒ 確定別家 ⇒ 不擋。
 * - **清單認不得** ⇒ 退 `issuerBank` 樣式路：判得出且是別家 ⇒ 確定別家；
 *   **判不出（`''`）⇒ 不確定 ⇒ 擋**——沒填、清單外文字、以及**`String()` 定型後仍認不出的壞資料**
 *   （`{bad:true}` → `"[object Object]"`）落在這格。
 * - ⚠️ **非字串不是一律算不確定**（Codex #522 r1 抓到我第一版把這格宣稱寫大了）：本支沿用 #520 的
 *   既有裁定「壞型別的答案＝它字串化之後的答案」（`test/card-issuers.test.js` 的容忍界線題釘著，
 *   並明寫「與使用者直接打那串字同義」）——所以 `['玉山銀行']` 被 `String()` 攤平成「玉山銀行」
 *   ⇒ 照字面判＝**確定別家、不擋**；`['台新']` 同理會被 `bankCards` 當同行。形狀是壞的、內容指向
 *   明確，照內容判與 #520 一致；要把「形狀壞」本身當不確定＝翻掉 #520 的裁定與考題，另案再議。
 *
 * ⚠️ **代價（裁示時攤開過）**：庫裡只要有一張「判不出發卡行」的信用卡，**所有**銀行的
 *    「單卡自動歸」都退成手選，直到把那張卡的發卡行填上（清單挑一下就好；候選清單裡看得到它）。
 *    取捨＝錢記錯卡不可逆、多按一次可逆——與 J5／J7 同一個哲學。
 * ⚠️ 這一支**只會**把「本來要自動」變成「請使用者選」，不會讓任何一張卡多拿到自動歸卡（方向單向）。
 * ⚠️ `bank` 空字串回 `false`（「沒有這一家」談不上確定不是）——但分支②在 `bank:''` 時
 *    `bankCards` 本來就是空的、走不到，這格是防呆不是承重（同 `cardMatchesBank` 的空機構名劃界）。
 *
 * 🔬 前一版守門的原始動機（工作流對抗驗證 2026-08-28 實測，Codex #520 四輪都沒看到）：
 *    兩張台北富邦卡（舊卡 issuer＝自由文字「富邦」、新卡＝清單正式寫法）＋末四碼讀不出來的富邦帳單
 *    ⇒ base 問使用者、只做清單化會自動歸到新卡——「不猜」若只做在 `issuerBank` 那一層，
 *    代價不是「多按一次」，而是**在別處多猜一次**。本判準把那個守門一併涵蓋（歧義含這家＝不確定）。
 *
 * @param {unknown} issuer @param {string} bank @returns {boolean}
 */
export function issuerCertainlyNot(issuer, bank) {
  if (!bank) return false;
  const named = issuersNamed(squash(String(issuer ?? '')));
  if (named.length) return named.every((o) => o.bank !== bank);
  const b = issuerBank(issuer);
  return b !== '' && b !== bank;
}

