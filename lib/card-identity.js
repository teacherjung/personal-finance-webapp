/** 民國日期（兩種模板）或西元日期——判「像不像交易列」用，刻意比解析器寬。 */
const dateish = (/** @type {string} */ s) => /^\d{2,3}\/\d{2}\/\d{2}$/.test(s) || /^1\d{6}$/.test(s) || /^\d{4}\/\d{2}\/\d{2}$/.test(s);
/** 金額樣（至少一位數字，允許千分位與小數）。 */
const amtish = (/** @type {string} */ s) => /^-?(?=[\d,]*\d)[\d,]+(\.\d+)?$/.test(String(s || '').trim());

/**
 * 這一列**像不像**交易列——用途只有一個：當「表頭區到哪裡為止」的分界。
 *
 * ⚠️ **判準看的是「整列文字切出來的詞」，不是「格」**（Codex #518 r2#2 實測）：
 *    前一版要求「至少三格、日期要獨占一格」，於是抽字把日期與商店塞進同一格的版面
 *    （`['115/07/01 星巴克', '100']` 只有兩格）就不算交易列 ⇒ **分界往後滑**，
 *    明細區的商店續行重新取得投票權。
 *    分界判錯的方向是**單向**的：判太嚴＝表頭區變大＝商店名有票（危險）；
 *    判太寬＝表頭區變小＝可能少看到真行名（安全，退到分支④）。所以這裡一律往「寬」倒。
 *
 * ⚠️ **刻意不與 `parseFubon`／`parseTaishinPdf` 的列判準共用**，即使長得像：抓交易時判太寬＝多一筆
 *    垃圾、判太嚴＝漏一筆錢；這裡的失敗方向如上、剛好相反。共用會逼其中一邊接受另一邊的取捨。
 *
 * @param {string[]} cells
 */
export const looksLikeTxRow = (cells) => {
  if (!Array.isArray(cells) || !cells.length) return false;
  const toks = cells.join(' ').split(/\s+/).filter(Boolean);
  return toks.some((t) => dateish(t)) && toks.some((t) => !dateish(t) && amtish(t));
};

/**
 * 自家內建範本的機構名樣式。⚠️ 這是**唯一實作**——`parsePdfAuto` 原本另外寫了一份全文計數版，
 * 已刪（同一件事兩把尺是這個 repo 反覆踩到的病）。
 *
 * ## ⚠️ 為什麼行名後面**必須**跟一個佐證詞（`銀行`／`信用卡`／`Bank`…）
 *
 * 因為**「一列之內非黏不可」**：真台新帳單的抬頭在文字層是 `['台','新','銀','行','綜','合',…]`
 * ——**一個字一格**（實測使用者三份真帳單，第 0 列都長這樣）。所以 `evidenceRows` 一定要把
 * 同一列的格黏起來，否則真行名永遠對不上。
 *
 * 但黏起來就會在**格與格的接縫**上長出假行名（Codex #518 r2#1 實測）：
 *   `['電子服務平台', '新戶刷卡禮']` → 黏成「電子服務平**台新**戶刷卡禮」⇒ 判成台新。
 * 不黏就讀不到真行名，所以改用**兩道結構限制**：
 *   ①**錨定在列的開頭**（`^`）——接縫上的假行名一定出現在列中間。
 *   ②行名後面要跟一個佐證詞（`銀行`／`國際商業銀行`／`信用卡`／`Bank`）。
 *
 * ⚠️ ①才是承重的那一道。r2 只做了②，Codex r3#1 當場找到三個繞法（「購物平**台新銀**座推薦」踩到
 *    單字「銀」、「某某TAI**SHIN**新戶推薦」與 Richart 踩到沒有邊界的英文分支）——**列舉佐證詞補不完**，
 *    所以改成關門：真行名印在抬頭、抬頭在列的開頭；接縫拼出來的一定不在開頭。
 *    實測真帳單：三份台新帳單的抬頭都在表頭區第 0 列命中；上述三個繞法全部不命中。
 * ⚠️ **誠實劃界**：仍不是「不可能誤判」——**列的開頭**剛好就是「台新銀行…」的版面還是會誤判
 *    （例如某家帳單第一列印的是「台新銀行代收」）。代價鏈是「誤判之後還要通過否證器、
 *    而且只影響歸卡建議與畫面標題」，不是這個正規式。
 * ⚠️ 錨定的代價：行名**不在列開頭**的版面會認不出來 ⇒ 分支④（多按一次選卡）。安全方向。
 * ⚠️ 曾經寫過 `/台\s*新/`，`\s` **吃換行**、把兩**列**拼成行名（r1#1）。現在比對逐列進行，那條通道
 * 已由結構堵掉；`\s` 在不在樣式裡已經沒有差別（突變實證：放回去沒有任何一題會紅），所以**不要**
 * 把「這裡沒有 `\s`」當成保證——真正承重的不變量是「比對永遠逐列進行」。
 * ⚠️ **已知繞法**：樣式錨定在**開頭**、沒有結尾錨 ⇒ `issuerBank('台北富邦銀行（香港）') === '富邦'`
 *    （前綴命中）。香港富邦的正式名稱從來不含「台北」，但發卡行清單把「台北富邦銀行」
 *    「富邦銀行（香港）」並排展示，使用者選「其他」自己拼出這種混合字串是可達的。
 *    **不能**加結尾錨修——帳單抬頭那條路要前綴匹配（「台北富邦銀行信用卡帳單」）；
 *    列舉否證詞補不完。要在結構上關掉＝發卡行改存機構代號（只有從清單挑的代號才授予身分）。
 * ⚠️ **富邦刻意只認「台北富邦」不認裸的「富邦」／`Fubon`**：`lib/bank-alias.js:17` 自己就記著
 *    「富邦香港 vs 台北富邦」是已知的撞名危害，而香港富邦確實發行信用卡。認錯家的代價是**自動歸到
 *    錯的卡**；不認的代價只是使用者多按一次選卡（分支④）。兩害相權取後者。
 *    ⚠️ 誠實劃界：若某一期台北富邦帳單**只印「富邦銀行」而沒印「台北富邦」**，這裡會認不出來 ⇒ 分支④。
 *    真帳單校準之前不放寬——放寬的代價落在錢上，不放寬的代價落在按鍵上。
 */
export const OWN_ISSUERS = /** @type {const} */ ([
  { bank: '台新', re: /^[台臺]新(國際商業銀行|商業銀行|銀行|信用卡|Bank)|^Taishin|^Richart/i },
  { bank: '富邦', re: /^[台臺]北富邦(商業)?銀行|^TaipeiFubon/i },
]);

/**
 * 一張卡片的**發卡行**是不是我們認得的那兩家。
 *
 * ## 兩把尺，一個共用的樣式
 *
 * ⚠️ **與「帳單是誰印的」共用同一組 `OWN_ISSUERS` 樣式**（撞名處理只有一個地方，不會走鐘），
 *    但**卡片欄位另外先查一次可選清單**（`public/modules/card-issuers.js`）——所以不是「完全同一把尺」。
 *    兩個資料域的輸入性質本來就不同：抬頭是 PDF 文字（格與格的接縫會長出假行名，所以要錨定＋佐證詞），
 *    卡片欄位是**使用者從清單挑的**（挑「台北富邦銀行」或「富邦銀行（香港）」是兩個不同的選項），
 *    外加清單化之前留下來的自由文字。
 * ⚠️ 這條路守的是錢：`String(issuer).includes(bank)`（base 的寫法）會讓
 *    `issuerMatchesBank('富邦銀行（香港）有限公司', '富邦')` **為真** ⇒ 台北富邦的帳單＋同末四碼的
 *    香港富邦卡 ⇒ 直接自動歸到那張香港卡（Codex #518 r3#2 實測）。`lib/bank-alias.js:17` 早就記著這個撞名危害。
 * ⚠️ 不能改用 `lib/bank-alias.js` 的 `sameBank`：那支只把**台新**收斂成短名，
 *    `sameBank('台北富邦銀行', '富邦')` 是 `false` ⇒ 會把富邦整個弄壞（實測）。
 *
 * @param {unknown} issuer @returns {string} '台新'|'富邦'|''（認不出）
 */
export function issuerBank(issuer) {
  const t = squash(String(issuer ?? ''));
  // ① 可選清單優先（2026-08-28，William 指派把發卡行從自由文字改成清單）。
  // ⚠️ **這一步不是「多一層保險」，它是承重的**：清單上的 `aka` 收得住既有的自由文字短名
  //    （「台新」「台北富邦」——`OWN_ISSUERS` 的樣式刻意要求錨定＋佐證詞，短名對不上），
  //    而**不接受短名**曾被判定為相對 base 的功能退化（Codex #518 r8#1）。拿掉這一步，
  //    既有的「台新」卡每期都要手選。
  const named = issuersNamed(t);
  if (named.length === 1) return named[0].bank;
  // ⚠️ **兩家以上都自稱這個寫法 ⇒ 不猜、也不落回樣式比對**。今天唯一的實例是「富邦」「富邦銀行」：
  //    香港富邦官方自稱「富邦銀行」、台北富邦官方沿革同樣記載這個簡稱（William 2026-08-28 查證），
  //    所以把香港卡的發卡行填成精確的「富邦」是合理且可達的輸入。判成台北富邦＝**錢記到錯的卡**；
  //    判不出來＝使用者多按一次選卡。兩害相權取後者，而清單就是那張卡的永久解（挑一項就沒有歧義了）。
  // ⚠️ **誠實劃界**：今天這一格的**行為**與「落回樣式比對」分辨不出來——「富邦」「富邦銀行」
  //    在 `OWN_ISSUERS` 底下本來就都不命中（樣式要求「台北富邦…銀行」），所以兩條路都回 `''`，
  //    突變成 `if (named.length) { /* 什麼都不做 */ }` 不會有任何一題轉紅。留著是因為它是這條規則的
  //    **正文**：日後只要有人把某一家的正式名稱登記成另一家的 `aka`，落回樣式比對就會給出錯的那一家。
  //    **不要把它當成保證**——承重的不變量是上面那句「兩家以上就不判身分」，而它由
  //    `test/card-issuers.test.js` 的「富邦／富邦銀行必須被兩家宣稱」那一題釘住資料面。
  if (named.length) return '';
  // ② 清單裡沒有這個寫法（自訂機構、或清單化之前的自由文字）⇒ 退回樣式比對。
  const hit = OWN_ISSUERS.filter((o) => o.re.test(t));
  // ⚠️ 「撞到兩家＝認不出」是 fail-closed 的**冗餘保險**：樣式都錨定在字串開頭，
  //    一個字串不可能同時以「台新…」與「台北富邦…」開頭 ⇒ 這一格目前**不可達**，
  //    突變測試也證實把它放寬成 `hit.length ?` 沒有任何一題會紅（等價突變）。
  //    留著是因為它零成本、而且樣式日後若拿掉錨定它就會變成承重的；但**不要當成保證**。
  return hit.length === 1 ? hit[0].bank : '';
}

/**
 * 這張卡的發卡行**有沒有可能**是 `bank`——即「寫法有歧義，而歧義的其中一家正是它」。
 *
 * ## 為什麼非有這一支不可（工作流對抗驗證 2026-08-28 抓到，Codex 四輪都沒看到）
 *
 * `issuerBank` 判不出身分時回 `''`，服務層的 `issuerMatchesBank` 因此回 `false`，那張卡就**被移出**
 * `bankCards`（`lib/services/statement-import.js` 的族群過濾）。但下游的分支②是一個**唯一性**判準
 * （`bankCards.length === 1` 就自動歸卡）——**把一個候選移出族群，會把「有歧義、該問使用者」
 * 靜靜變成「只有一張、自動歸卡」**。
 *
 * 🔬 實測（base `a3cdd6b` vs 本支）：使用者有兩張台北富邦卡，舊那張的 `issuer` 是自由文字「富邦」、
 *    新那張是「台北富邦銀行」；帳單認得出 `bank:'富邦'` 但末四碼讀不出來。
 *      base：兩張都算同行卡 ⇒ **有歧義 ⇒ 請使用者選**（安全）
 *      只做清單化：舊卡被判不出身分而出局 ⇒ **只剩一張 ⇒ 自動歸到新卡**（危險）
 *    ⇒ 本支的「不猜」如果只做到 `issuerBank` 那一層，代價**不是**「多按一次選卡」，
 *    而是**在別的地方多猜了一次**。那正好推翻本支自己的立論，所以非補不可。
 *
 * ⚠️ 判準是「**歧義**」而不是「認不出」：完全認不出的寫法（`玉山銀行`、`某某會員俱樂部`）本來就不是
 *    這一家，移出族群是對的；只有「兩家以上都叫這個名字、而其中一家正是 `bank`」才叫「可能是」。
 * ⚠️ 這一支**不放寬自動歸卡**——它只會讓「本來要自動」變成「請使用者選」，方向單向。
 *
 * @param {unknown} issuer @param {string} bank @returns {boolean}
 */
export function issuerMaybeBank(issuer, bank) {
  if (!bank) return false;
  const named = issuersNamed(squash(String(issuer ?? '')));
  return named.length > 1 && named.some((o) => o.bank === bank);
}

