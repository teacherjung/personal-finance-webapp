// @ts-check
// 右下角提示要停留多久：**訊息多長就給多久**。
//
// 為什麼需要這一檔（r1 審查者實測抓到的洞）：`public/app.js` 的 `toast()` 原本固定 3.2 秒就把訊息移除，
// ⚠️ **2026-08-08 訂正（原文以下保留作沿革）**：William 兩輪縮短之後，匯出文案已經是
//    **一行、12–18 字**（成功那句尾巴掛檔名與筆數），而且「把這句話整句告訴我」那個指令
//    整句拿掉了。所以下面「40–100 字」「兩句叫他整句告訴我」講的是**縮短之前**的狀態。
//    ⚠️ 但這一支的價值不變：**提示停留時間照字數給**（成功那句含長檔名仍可能偏長），
//    而「短句 3.2 秒夠」正是縮短之後仍要守住的下限。
// 而這一支 PR 的匯出文案是 40–100 字上下——3.2 秒內要讀完得每秒十幾到快三十個字。
// 也就是說「按下去會說話」這個保證整個押在**使用者讀得到**，卻被投遞機制否決了：
// 更糟的是其中兩句叫他「把這句話整句告訴我（⚠️ 2026-08-08 起這個指令已隨文案縮短移除，見下）」，而那句話幾秒後就不存在、也沒有任何地方能回看。
// （對照：全 app 其他提示的字面中位數不到十個字，3.2 秒對**短句**是夠的——所以不是把時間一律加長，
//  而是照長度給。）
//
// 為什麼獨立成一支純模組：`public/app.js` 在 node 裡 import 不進來（模組頂層就碰 document／localStorage），
// 時間怎麼算若寫在 app.js 裡就**沒有考題撐得住**。這一檔零 import、零 DOM，
// 考題＝`test/toast-timing.test.js`（「app.js 真的用它」由那份考題的原始碼文字題盯著）。
//
// ── 誠實劃界（這一支**不**保證什麼）──────────────────────────────────────────
// 1. 只管「停多久」。它**不會**讓訊息可以事後回看——這個 app 沒有提示紀錄本，
//    訊息消失之後就真的沒有了（滑鼠停在上面會暫停、可以選字複製，那是 app.js 那一端做的）。
// 2. 不保證他讀了，也不保證他讀得懂——只保證時間夠。
// 3. 每字時間是**照一位不習慣讀螢幕的人**估的（不是實測某個人的閱讀速度），寧可偏慢。

/** 短句的時間下限（毫秒）：全 app 大多數提示只有幾個字，這個值是它們原本就有的時間，刻意不動。 */
export const TOAST_MIN_MS = 3200;
/** 每個字給多久（毫秒）：約每秒四個字，偏慢是刻意的——提示只出現一次，讀不完就等於沒說。 */
export const TOAST_MS_PER_CHAR = 260;
/**
 * 停留時間上限（毫秒）：再長也不能一直卡在畫面右下角。
 *
 * ⚠️ 這個上限咬到誰＝**訊息太長了**：長到 `TOAST_MAX_MS / TOAST_MS_PER_CHAR` 字以上，
 *    考題〈每一句都讀得完〉就會紅。那時該做的是**把訊息拆短**（短提示 ＋ `openInfo(...)` 放完整說明），
 *    不是把這個上限調高——一則講不完的話塞在提示裡，本來就不該用提示講。
 */
export const TOAST_MAX_MS = 30_000;

/**
 * 這則訊息該在畫面上停多久（毫秒）。
 *
 * ⚠️ 用「字數」而不是「詞數」：中文沒有空白分詞，而這個 app 的提示幾乎全是中文。
 * @param {string} msg 提示文字（非字串／空值一律當空字串，回下限——寧可短也不要丟錯）
 * @returns {number} 毫秒，介於 {@link TOAST_MIN_MS} 與 {@link TOAST_MAX_MS} 之間
 */
export function toastMs(msg) {
  const len = String(msg ?? '').length;
  return Math.min(TOAST_MAX_MS, Math.max(TOAST_MIN_MS, Math.round(len * TOAST_MS_PER_CHAR)));
}
