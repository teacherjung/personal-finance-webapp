/**
 * 設定頁那張卡要送出的 patch。**清除優先**（順序同 `saveTaishinSecPw` 的既有慣例）：
 * - 勾了清除 ⇒ `{ aiApiKey: '' }`（明確送空字串＝清空）
 * - 沒勾、有打字 ⇒ `{ aiApiKey: 值 }`。⚠️ **trim**：API key 從網頁複製極容易帶尾端換行，
 *   帶空白的鑰匙不會當場報錯，會等到下次上傳帳單才炸成 `ai_auth`（使用者以為鑰匙壞了）。
 * - 沒勾、也沒打（或只打了空白）⇒ `null`＝**沒有變更**（呼叫端紅字提示、不送 PUT）。
 *   ⚠️ 這一條就是「留空不會把已存的鑰匙清掉」的保證：寫成無條件送 `val()` 會讓使用者一按儲存就清空。
 * @param {{value?: any, clear?: any}} o @returns {{aiApiKey: string}|null}
 */
export function aiKeyPatch({ value, clear } = {}) {
  if (clear === true) return { aiApiKey: '' };
  const v = typeof value === 'string' ? value.trim() : '';
  return v ? { aiApiKey: v } : null;
}

