// @ts-check
/**
 * 量 **CPU 時間**（user＋system，毫秒），不量牆上時鐘。給「數量級」門檻類的考題用
 * （CPU 密集的壞法：每筆重算的 Θ(n³)、正則二次方回溯……）。
 *
 * ⚠️ 為什麼（2026-09-03）：這類題原本用 `Date.now()`，而 pre-push 會在**每個 session** 跑全卷、
 *    `node --test` 又把考題檔平行開到核心數——同一台機器有兩三個 session 同時在推時，本行程排不到 CPU，
 *    牆上時鐘照走、門檻就紅（#547 記錄的「與本支無關的時間門檻題」）。
 *    實測（4 核容器、32 個忙迴圈當背景）：`test/multi-currency-account.test.js` 的牆上時鐘版三跑三紅
 *    （note() 那一段 1ms 的工作量被拖過 500ms 門檻）；換成本函式後同樣壓力三跑三綠。
 *    CPU 時間只算本行程真的算了多少，別人搶走 CPU 不算進來——而這些題守的本來就是「算了多少」，不是「等了多久」。
 *
 * ⚠️ 這是一個**交換**，不是白拿（Codex #552 r1 抓到我原本寫的「本函式不讓門檻變鬆」是假話）：
 *    ・**換掉量尺＝換掉守得住的壞法族**。CPU 時間只算本行程在算的時間：同步等待（`Atomics.wait`、同步 I/O）、
 *      丟給子行程再同步等結果（`process.cpuUsage()` 不含子行程）——在這種量法下都量成 0。
 *      實測：`Atomics.wait` 650ms ⇒ 牆上 655ms／CPU 0ms；`spawnSync` 跑 250ms 忙迴圈的子行程 ⇒ 牆上 322ms／CPU 1ms。
 *      也就是說，**用本函式的題不再是「這段必須在 X 毫秒內做完」**，而是「這段的 CPU 工作量必須在 X 毫秒內」；
 *      若有人日後在受測路徑裡塞進同步等待或子行程，這些題不會紅——那要靠別的題守。
 *      目前用它的五題受測的都是純同步計算的函式（`makeCurrencyTable().note/finalize`、`parseCardWithRecipe`
 *      的金額形判準），路徑上本來就沒有 I/O；這個交換是在「壓力下假紅」與「放掉一族這裡沒有的壞法」之間選了後者。
 *    ・**題名與斷言訊息要用 CPU 工作量的語意寫**（「不燒 CPU」「工作量毫秒級」），不要寫「立刻」「毫秒級收工」
 *      那種牆上延遲語意——那是本函式證明不了的。
 *    ・門檻數字沒動，但**「距離」要用新量尺重量**：各題註解裡引用的舊實測（8.38 秒／6 秒／5,115ms／兩秒級）
 *      全是牆上時鐘量的，只能當歷史。用本函式重量過的壞法：每筆重算的 Θ(n³)（300 列）＝ CPU 10,148ms
 *      （Codex r1 獨立量到 10,303ms）；夾心正則二次方回溯（單格 5 萬字元）＝ CPU 4,240ms（Codex r1 3,957ms）
 *      ——對 500ms／1,500ms 的門檻各留二十倍與近三倍。另外兩題（單鍵超長、計算量預算）拿掉守門會先被
 *      `assert.throws` 的行為斷言抓到，時間斷言守的是「有拒收、但拒收前先算了很久」，沒有對應的 CPU 壞法實測值。
 *    ・**CPU 時間在競爭下會膨脹多少，沒有上界可保證**：同核心競爭（快取、超執行緒）會讓同一份工作吃更多 CPU；
 *      多執行緒的工作（worker）算在同一個行程，CPU 時間甚至可以**大於**牆上時鐘。本函式只保證「別的行程搶走的
 *      時間不算進來」，不保證數字穩定——所以門檻與壞法之間要留倍數距離，不能貼著自然值設。
 *    ・**只適用 CPU 密集的同步工作**。等 timer、等 I/O、等子行程那類「必須在 X 毫秒內回應」的題
 *      （例：`test/stock-fundamentals-api.test.js` 的佇列總時限、`test/pdf-isolate.test.js` 的「自己死的不該等到逾時」、
 *      `test/pr-base-version.test.js` 的子行程逾時）量的本來就是牆上時鐘，換成本函式會把它們量成 0——
 *      那些題在壓力下的間歇紅要另外處理，不在本函式射程。
 * @param {() => void} fn 同步工作；回傳它消耗的 CPU 毫秒（fn 丟出的例外原樣傳出，不吞）
 */
export const cpuMs = (fn) => { const u0 = process.cpuUsage(); fn(); const u = process.cpuUsage(u0); return (u.user + u.system) / 1000; };
