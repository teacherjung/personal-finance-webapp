// @ts-check
/**
 * 量 **CPU 時間**（user＋system，毫秒），不量牆上時鐘。給「數量級」門檻類的考題用
 * （CPU 密集的壞法：每筆重算的 Θ(n³)、正則二次方回溯……）。
 *
 * ⚠️ 為什麼（2026-09-03）：這類題原本用 `Date.now()`，而 pre-push 會在**每個 session** 跑全卷、
 *    `node --test` 又把考題檔平行開到核心數——同一台機器有兩三個 session 同時在推時，本行程排不到 CPU，
 *    牆上時鐘照走、門檻就紅（#547 記錄的「與本支無關的時間門檻題」）。
 *    實測（4 核容器、32 個忙迴圈當背景）：`test/multi-currency-account.test.js` 的牆上時鐘版三跑三紅
 *    （note() 那一段 1ms 的工作量被拖過 500ms 門檻）；換成本函式後同樣壓力三跑三綠。
 *    CPU 時間只算本行程真的算了多少，別人搶走 CPU 不算進來——而這些題守的本來就是「算了多少」，不是「等了多久」。
 *
 * ⚠️ 誠實劃界：
 *    ・CPU 時間在同核心競爭（快取、超執行緒）下仍會膨脹，但是幾成、不是幾倍；用本函式的題，門檻與壞法
 *      之間要留幾倍以上的距離（各題註解裡的實測值），才吃得下這種膨脹。**本函式不讓門檻變鬆**——
 *      改用它的題門檻數字一個都沒動，改的只有量的是哪一種時間。
 *    ・**只適用 CPU 密集的同步工作**。等 timer、等 I/O、等子行程那類「必須在 X 毫秒內回應」的題
 *      （例：`test/stock-fundamentals-api.test.js` 的佇列總時限、`test/pdf-isolate.test.js` 的「自己死的不該等到逾時」）
 *      量的本來就是牆上時鐘，換成本函式會把它們量成 0——那些題在壓力下的間歇紅要另外處理，不在本函式射程。
 * @param {() => void} fn 同步工作；回傳它消耗的 CPU 毫秒
 */
export const cpuMs = (fn) => { const u0 = process.cpuUsage(); fn(); const u = process.cpuUsage(u0); return (u.user + u.system) / 1000; };
