  // ⚠️ 「第 12 條從哪裡到哪裡」一律問 `ruleItemRange()`（判準＝CommonMark 的內容欄，正反例表在
  //    `test/agents-rule-item.test.js`）。**不要在這裡自己寫一條「下一條長什麼樣」的正規式**——
  //    第一版就是那樣寫的，#585 r2 用四種合法寫法（一格空白／點號後 tab／三格縮排／`13)`）全部打穿。
