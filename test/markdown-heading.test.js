// `test/helpers/markdown-heading.js` 的正反例表。
// 為什麼要有：那支 helper 守的是「有人整理文件時，把安全契約那一節收進一個新的小節」。
// 它在 #578 被獨立審查者反覆打穿，而每一輪修完都**沒有固定夾具守著**——把修正退回去，
// 依賴它的那道文件考題照樣全綠（#578 r11 Low⑤ 實測）。這張表就是那個缺口的補丁。
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { headingAt } from './helpers/markdown-heading.js';

/** @param {string} md @param {number} i */
const level = (md, i) => headingAt(md.split('\n'), i);

test('⭐ 該判成標題的：ATX（William 2026-09-07 裁示留下的唯一一種）', () => {
  for (const [name, md, i, want] of [
    ['H1', '# 標題', 0, 1],
    ['H3', '### 標題', 0, 3],
    ['帶三格縮排', '   ## 標題', 0, 2],
    ['井號後直接行尾', '##', 0, 2],
    ['H6', '###### 標題', 0, 6],
    ['井號後接 tab', '##\t標題', 0, 2],
  ]) {
    assert.equal(level(/** @type {string} */ (md), /** @type {number} */ (i)), want, `${name}：應該判成 H${want}`);
  }
});

test('⭐ 不該判成標題的：正常編修會用到的形狀（誤擋會卡住寫文件的人）', () => {
  for (const [name, md, i] of [
    // AGENTS.md:356 的真實內文，就坐在鏈最嚴格的那一段裡；`(?:[ \t]|$)` 是唯一擋著它的東西
    ['井號緊接數字（AGENTS.md 的真內文）', '  #348（2026-08-02 合併）裁決「規則收下、工具不收」', 0],
    ['井號後面沒有空白', '#標題', 0],
    ['七個井號', '####### 太多了', 0],
    ['井號不在行首', '前文 # 不是標題', 0],
    ['四格縮排（ATX 最多三格）', '    # 這是縮排', 0],
    // 以下是 William 2026-09-07 裁示**明講擋不到**的（不是漏掉）
    ['Setext H2（裁示：擋不到）', '一段話\n---', 1],
    ['Setext H1（裁示：擋不到）', '一段話\n===', 1],
    ['raw HTML 標題（裁示：擋不到）', '前文 <h4>以下整節已作廢</h4>', 0],
    // 容器裡的標題只能重新分配那個容器內部的內容，而本節不在任何容器裡
    ['清單項同行的井號（容器內）', '- # 這其實會渲染成標題，但換不走本節的爸爸', 0],
    ['引言裡的井號（容器內）', '> # 同上', 0],
  ]) {
    assert.equal(level(/** @type {string} */ (md), /** @type {number} */ (i)), 0, `${name}：不可以判成標題`);
  }
});

test('⭐ 刻意不做隱藏區掃描：圍欄與 HTML 註解裡長得像 ATX 的行**照樣算標題**（可能假紅，這是刻意的取捨）', () => {
  // 歷史量測：`git log -p --follow -- AGENTS.md` 的 1281 行新增裡，圍欄 0 行、HTML 註解 0 行。
  // 那些例外規則守到的量是 0，卻是 #578 r9〜r14 幾乎每一條 High 的來源（「看起來像隱藏區、
  // 其實不是」與「落單記號讓後面整片靜音」）。拿掉之後這支只會更紅，不會更鬆。
  assert.equal(level('```\n# 這在圍欄裡\n```', 1), 1, '圍欄裡的 ATX 照樣算——寧可假紅，也不要留一個能靜音的掃描器');
  assert.equal(level('<!--\n# 這在註解裡\n-->', 1), 1, 'HTML 註解裡的 ATX 照樣算，理由同上');
  // ⚠️ 反過來的保證也要成立：**沒有任何東西能讓偵測靜音**。
  assert.equal(level('```\n前文\n# 真的標題', 2), 1, '落單的圍欄記號不可以讓後面的真標題被放過');
  assert.equal(level('<!--\n前文\n# 真的標題', 2), 1, '沒關門的註解不可以讓後面的真標題被放過');
  assert.equal(level('維護語法：`<!--`\n# 真的標題', 1), 1, '行內程式碼裡的註解記號更不可以');
});
